import assert from 'node:assert/strict'
import fs from 'node:fs'
import { transformWithEsbuild } from 'vite'

const src = fs.readFileSync('src/components/devices/availability.ts', 'utf8')
const compiled = await transformWithEsbuild(src, 'availability.ts', { loader: 'ts', format: 'esm' })
const { formatDeviceAvailability: format, deviceAvailabilityBuckets: buckets, packetLossPercent, averageDevicePacketLoss } = await import(`data:text/javascript;base64,${Buffer.from(compiled.code).toString('base64')}`)
assert.equal(format(99.96), '99.96%')
assert.equal(format(100), '100.00%')
assert.equal(format(0), '0.00%')
for (const value of [null, undefined, NaN, Infinity]) assert.equal(format(value), '—')
const from = Date.parse('2026-09-01T00:00:00Z'), to = from + 3600000
const point = (offset, pct, count, legacy = true) => ({ timestamp: new Date(from + offset).toISOString(), is_up: legacy, uptime_pct: pct, sample_count: count })
const result = buckets([point(0, 99.96, 40000)], from, to)
assert.equal(result[0].state, 'partial')
assert.equal(Math.round(result[0].down), 16)
assert.equal(format(result[0].pct), '99.96%')
assert(result.slice(1).every(b => b.state === 'gap'))
const weighted = buckets([point(0, 100, 99), point(1, 0, 1, false)], from, to)[0]
assert.equal(weighted.pct, 99)
assert.equal(weighted.down, 1)
assert.equal(weighted.state, 'partial')
assert.equal(buckets([point(0, 0, 10, false)], from, to)[0].state, 'down')
assert.equal(buckets([point(0, null, 0, null)], from, to)[0].state, 'gap')
assert.equal(buckets([{timestamp: new Date(from).toISOString(), is_up: false}], from, to)[0].state, 'down')
assert(buckets([point(-1, 0, 10), point(3600001, 0, 10), {timestamp:'invalid', is_up:false}], from, to).every(b => b.state === 'gap'))
// The Events tab's availability card: headline from the shared uptime-stats calculation for this device,
// over the exact selected window, with two decimals; failed checks stay diagnostic evidence.
const card = fs.readFileSync('src/pages/device/AvailabilityCard.tsx', 'utf8')
const hooks = fs.readFileSync('src/pages/device/hooks.ts', 'utf8')
const eventsTab = fs.readFileSync('src/pages/device/EventsTab.tsx', 'utf8')
assert(card.includes('function AvailabilityTimelineCard('), 'the timeline card lives in AvailabilityCard.tsx')
const section = card.slice(card.indexOf('function AvailabilityTimelineCard('))
assert(section.includes('const pct = availabilityPct ?? null'))
assert(!section.includes('upCount / total'))
assert(section.includes('formatDeviceAvailability(pct)'), 'headline keeps two decimals')
assert(card.includes('const availabilityPct = availability.data?.devices?.[id]'), 'headline is the shared per-device uptime-stats value')
assert(card.includes('availabilityPct={availabilityPct}'))
assert(card.includes('useDeviceAvailability(id, range, enabled)'), 'headline uses the shared hook with the page range')
assert(eventsTab.includes('<AvailabilityCard device={device} range={range} />'), 'the Events tab shows the availability card')
assert(!/#[0-9a-fA-F]{6}\b/.test(card), 'availability strip uses theme tokens')
assert(!/text-\[(9|10|11)px\]/.test(card), 'availability labels are at least 12 px')
console.log('Device availability regressions passed: 99.96% precision, partial failures, sample weighting, missing data, range bounds, and shared headline source.')

assert(hooks.includes("queryKey: ['uptime-stats', range.fromISO, range.toISO, id]"), 'same-duration historical windows must not share current-window cache')
assert(hooks.includes('/devices/dashboard/uptime-stats?from=${encodeURIComponent(range.fromISO)}&to=${encodeURIComponent(range.toISO)}&device_id=${id}'), 'headline and timeline must request identical dates')
assert(card.includes('/availability-events?from=${encodeURIComponent(range.fromISO)}&to=${encodeURIComponent(range.toISO)}'), 'confirmed outages use the same window')
assert(card.includes('usePingMetrics(id, range, enabled)'), 'the strip uses the same window')
assert(section.includes('aria-pressed={i === activeIndex}'), 'selected interval is accessible')
assert(section.includes('Outage history could not be loaded'), 'failed incident query must remain unknown')

assert.equal(packetLossPercent(1), 100, 'complete loss must display 100%, not 1%')
assert.equal(packetLossPercent(.01), 1)
assert.equal(packetLossPercent(0), 0)
for (const ratio of [null, undefined, NaN, Infinity, -1, 2]) assert.equal(packetLossPercent(ratio), null)
assert.equal(averageDevicePacketLoss([{packet_loss:1,sample_count:3}]),100)
assert.equal(averageDevicePacketLoss([{packet_loss:1,sample_count:1},{packet_loss:0,sample_count:99}]),1, 'rollup averages must be sample weighted')
assert.equal(averageDevicePacketLoss([{packet_loss:null,sample_count:100},{packet_loss:1,sample_count:0}]),null)
assert.equal(averageDevicePacketLoss([{packet_loss:0},{packet_loss:1}]),50, 'legacy raw points default to one check each')
assert.equal(averageDevicePacketLoss([]),null)
console.log('Packet-loss units, weighted rollups, complete loss and missing data passed.')
