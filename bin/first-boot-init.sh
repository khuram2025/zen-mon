#!/bin/bash
# ZenPlus first-boot initialization.
# Runs on every boot but only does work if the sentinel is missing.
# On any failure, exits non-zero WITHOUT writing the sentinel, so
# dependent services (Requires=) refuse to start and the operator
# sees a clear failed unit instead of a running-but-broken appliance.
set -euo pipefail

SENTINEL=/var/lib/zenplus/.initialized
ENV_FILE=/opt/zenplus/.env
LOG_DIR=/var/log/zenplus
LOG_FILE="$LOG_DIR/first-boot.log"

mkdir -p "$LOG_DIR" /var/lib/zenplus
chmod 755 "$LOG_DIR"
exec >>"$LOG_FILE" 2>&1

echo
echo "=== first-boot-init starting $(date -Is) ==="

if [ -f "$SENTINEL" ]; then
    echo "Sentinel $SENTINEL present — already initialized, exiting."
    exit 0
fi

fail() { echo "FAIL: $*"; exit 1; }

echo "[1/7] waiting for postgres..."
for i in $(seq 1 60); do
    pg_isready -h localhost -q && break
    sleep 2
done
pg_isready -h localhost -q || fail "postgres not ready after 120s"

echo "[2/7] waiting for docker..."
for i in $(seq 1 60); do
    docker info >/dev/null 2>&1 && break
    sleep 2
done
docker info >/dev/null 2>&1 || fail "docker not ready after 120s"

echo "[3/7] waiting for redis..."
for i in $(seq 1 30); do
    [ "$(systemctl is-active redis-server)" = "active" ] && break
    sleep 1
done
[ "$(systemctl is-active redis-server)" = "active" ] || fail "redis not active"

echo "[4/7] generating secrets and writing .env..."
PG_PASS=$(openssl rand -hex 16)
CH_PASS=$(openssl rand -hex 16)
RD_PASS=$(openssl rand -hex 16)
JWT=$(openssl rand -hex 32)

umask 077
cat >"${ENV_FILE}.tmp" <<EOF
# Generated by first-boot-init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# DO NOT DELETE — contains database credentials.
POSTGRES_PASSWORD=${PG_PASS}
CLICKHOUSE_PASSWORD=${CH_PASS}
REDIS_PASSWORD=${RD_PASS}
JWT_SECRET=${JWT}
API_HOST=0.0.0.0
API_PORT=8000
DATABASE_URL=postgresql+asyncpg://zenplus:${PG_PASS}@localhost:5432/zenplus
CLICKHOUSE_HOST=localhost
CLICKHOUSE_PORT=9000
CLICKHOUSE_HTTP_PORT=8123
CLICKHOUSE_DB=zenplus
CLICKHOUSE_USER=default
REDIS_URL=redis://:${RD_PASS}@localhost:6379/0
POLLER_ID=poller-01
POSTGRES_HOST=localhost
POSTGRES_PORT=5432
POSTGRES_DB=zenplus
POSTGRES_USER=zenplus
REDIS_HOST=localhost
REDIS_PORT=6379
EOF
chown zenplus:zenplus "${ENV_FILE}.tmp"
chmod 640 "${ENV_FILE}.tmp"
mv "${ENV_FILE}.tmp" "$ENV_FILE"

echo "[5/7] configuring postgres, redis, clickhouse..."

# --- Postgres ---
sudo -u postgres psql -v ON_ERROR_STOP=1 <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='zenplus') THEN
    EXECUTE 'CREATE USER zenplus WITH PASSWORD ' || quote_literal('${PG_PASS}');
  ELSE
    EXECUTE 'ALTER USER zenplus WITH PASSWORD ' || quote_literal('${PG_PASS}');
  END IF;
END\$\$;
SQL
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='zenplus'" | grep -q 1 \
    || sudo -u postgres psql -c "CREATE DATABASE zenplus OWNER zenplus;"
sudo -u postgres psql -d zenplus -c "CREATE EXTENSION IF NOT EXISTS pgcrypto;" >/dev/null

# --- Redis ---
# Strip any `user default` ACL line (shadows requirepass), rewrite the
# password, and restart. zenplus-first-boot.service must NOT have
# Requires=redis-server or the restart will SIGTERM us.
sed -i '/^user default /d' /etc/redis/redis.conf
if grep -qE '^[#[:space:]]*requirepass[[:space:]]' /etc/redis/redis.conf; then
    sed -i -E "s|^[#[:space:]]*requirepass[[:space:]].*|requirepass ${RD_PASS}|" /etc/redis/redis.conf
else
    echo "requirepass ${RD_PASS}" >>/etc/redis/redis.conf
fi
awk 'BEGIN{seen=0} /^requirepass / {if (seen) next; seen=1} {print}' \
    /etc/redis/redis.conf > /etc/redis/redis.conf.tmp \
    && mv /etc/redis/redis.conf.tmp /etc/redis/redis.conf
chown redis:redis /etc/redis/redis.conf 2>/dev/null || true
chmod 640 /etc/redis/redis.conf

systemctl restart redis-server
for i in $(seq 1 30); do
    redis-cli -a "$RD_PASS" --no-auth-warning ping 2>/dev/null | grep -q PONG && break
    sleep 1
done
redis-cli -a "$RD_PASS" --no-auth-warning ping 2>/dev/null | grep -q PONG \
    || fail "redis not reachable with new password after restart"

# --- ClickHouse ---
cd /opt/zenplus && docker compose up -d
for i in $(seq 1 60); do
    docker exec zenplus-clickhouse clickhouse-client --password "$CH_PASS" --query "SELECT 1" >/dev/null 2>&1 && break
    sleep 2
done
docker exec zenplus-clickhouse clickhouse-client --password "$CH_PASS" --query "SELECT 1" >/dev/null 2>&1 \
    || fail "clickhouse not ready after 120s"

for sql_file in scripts/init-clickhouse.sql scripts/fix-clickhouse.sql scripts/migrate-*-clickhouse.sql; do
    [ -f "$sql_file" ] || continue
    echo "running ClickHouse migration: $(basename "$sql_file")"
    docker cp "$sql_file" zenplus-clickhouse:/tmp/m.sql
    docker exec zenplus-clickhouse clickhouse-client --password "$CH_PASS" --multiquery --queries-file /tmp/m.sql >/dev/null 2>&1 || true
done

# --- Reset subscription to fresh 30-day trial ---
# Gated by sentinel, so runs exactly once per imported appliance.
# Order matters: the API re-syncs subscription state from
# /opt/zenplus/updater/config/subscription.json on every request, and
# that JSON is written by the updater agent using the creds in
# agent.conf. We must therefore (a) delete the cached JSON, (b) clear
# the appliance creds so the updater can't immediately re-fetch the
# old remote state, and (c) only then reset the DB row.
echo "[6/8] clearing OTA registration and resetting subscription..."
rm -f /opt/zenplus/updater/config/subscription.json

AGENT_CONF=/opt/zenplus/updater/config/agent.conf
if [ -f "$AGENT_CONF" ]; then
    # Blank the appliance id + api_key so the updater must re-register
    # (customer registers by entering a license key in Settings).
    sed -i -E 's|^(id[[:space:]]*=).*|\1|; s|^(api_key[[:space:]]*=).*|\1|' "$AGENT_CONF"
    chown zenplus:zenplus "$AGENT_CONF"
fi

sudo -u postgres psql -d zenplus -v ON_ERROR_STOP=1 <<'SQL' >/dev/null
DELETE FROM subscriptions;
INSERT INTO subscriptions (plan, status, started_at, expires_at,
                           max_devices, max_service_checks, max_users,
                           license_key, activated_by)
VALUES ('trial', 'active', now(), now() + INTERVAL '30 days',
        50, 20, 5, NULL, NULL);
SQL

echo "[7/8] generating first-login admin password..."
ADMIN_TEMP_PASSWORD="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 20)"
ADMIN_HASH=$(/opt/zenplus/venv/bin/python3 - "$ADMIN_TEMP_PASSWORD" <<'PY'
import sys
from passlib.context import CryptContext

password = sys.argv[1]
print(CryptContext(schemes=["bcrypt"], deprecated="auto").hash(password))
PY
)
sudo -u postgres psql -d zenplus -v ON_ERROR_STOP=1 -v admin_hash="$ADMIN_HASH" <<'SQL' >/dev/null
UPDATE users
SET password_hash = :'admin_hash',
    last_login = NULL,
    updated_at = NOW()
WHERE username = 'admin';
SQL

install -d -m 0750 -o root -g root /var/lib/zenplus
umask 077
cat >/var/lib/zenplus/initial-admin-password <<EOF
ZenPlus initial web login
Username: admin
Password: ${ADMIN_TEMP_PASSWORD}

Change this password immediately after first login.
EOF
chmod 0600 /var/lib/zenplus/initial-admin-password

{
    echo
    echo "============================================================"
    echo " ZenPlus initial web login"
    echo " URL:      https://$(hostname -I 2>/dev/null | awk '{print $1}')/"
    echo " Username: admin"
    echo " Password: ${ADMIN_TEMP_PASSWORD}"
    echo " Change this password immediately after first login."
    echo "============================================================"
    echo
} >/dev/tty1 2>/dev/null || true

# --- Verify ---
echo "[8/8] verifying..."
PGPASSWORD="$PG_PASS" psql -h localhost -U zenplus -d zenplus -tAc "SELECT 1" | grep -q 1 \
    || fail "postgres auth verification"
redis-cli -a "$RD_PASS" --no-auth-warning ping 2>/dev/null | grep -q PONG \
    || fail "redis auth verification"
docker exec zenplus-clickhouse clickhouse-client --password "$CH_PASS" --query "SELECT 1" | grep -q 1 \
    || fail "clickhouse verification"
test -s /var/lib/zenplus/initial-admin-password \
    || fail "initial admin password file missing"

touch "$SENTINEL"
chmod 644 "$SENTINEL"
echo "=== first-boot-init complete $(date -Is) ==="
