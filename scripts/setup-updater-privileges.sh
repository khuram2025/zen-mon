#!/bin/bash
# ============================================================================
# ZenPlus updater privileges
#
# What the zenplus service account (the API) may do to the OTA updater:
#   - start zenplus-updater.service ("Check for update"), via sudo
#   - set the updater check interval, via the root-owned
#     /usr/local/sbin/zenplus-updater-timer-helper, which accepts a number and
#     writes a fixed [Timer] drop-in
#
# This replaces the older grants:
#   - `sudo tee /etc/systemd/system/zenplus-updater.timer.d/override.conf`,
#     which accepted arbitrary drop-in content (for example Unit=reboot.target)
#   - the `mkdir`, `daemon-reload` and `restart zenplus-updater.timer` sudo lines
#     the tee flow needed
#   - zenplus-updater.pkla, which on polkit < 0.106 (Ubuntu 20.04/22.04)
#     granted manage-units for EVERY unit. polkit < 0.106 now gets no grant at
#     all: the API only uses sudo. The narrow .rules file (updater units only)
#     is kept on polkit >= 0.106.
#
# Run by install.sh, scripts/setup-updater.sh and as a hook on every OTA update.
# Idempotent. Never touches a timer drop-in it did not write except to remove
# one that is not a plain managed interval.
#   sudo bash scripts/setup-updater-privileges.sh
# ============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ZENPLUS_DIR="${ZENPLUS_DIR:-/opt/zenplus}"
SERVICE_USER="zenplus"
HELPER_SRC="${SCRIPT_DIR}/zenplus-updater-timer-helper"
HELPER_DST="/usr/local/sbin/zenplus-updater-timer-helper"
SUDOERS="/etc/sudoers.d/zenplus-updater"
RULES_SRC="${ZENPLUS_DIR}/updater/polkit/50-zenplus-updater.rules"
# Typed privilege broker of the VMware appliance image: it owns the sudoers
# policy there (and rewrites it after every updater run).
OVA_BROKER="/usr/local/libexec/zentryc-privileged"

log()  { echo "[setup-updater-privileges] $1"; }
warn() { echo "[setup-updater-privileges] WARNING: $1" >&2; }

if [ "$(id -u)" -ne 0 ]; then
    echo "This script must run as root (sudo bash scripts/setup-updater-privileges.sh)" >&2
    exit 1
fi

# ── 1. Timer helper ─────────────────────────────────────────────────────────
# The root-owned installed copy is the security boundary; sudoers never points
# into /opt/zenplus.
if [ ! -f "${HELPER_SRC}" ] || [ -L "${HELPER_SRC}" ]; then
    warn "${HELPER_SRC} missing or not a regular file"
    exit 1
fi
install -o root -g root -m 0755 "${HELPER_SRC}" "${HELPER_DST}"
log "Installed ${HELPER_DST}"

# ── 2. Sudoers ──────────────────────────────────────────────────────────────
# Each line corresponds to an exact subprocess.run() call in
# server/app/api/v1/system_updates.py; do not broaden them.
if [ -x "${OVA_BROKER}" ]; then
    log "Typed privilege broker present; leaving its sudoers policy unchanged"
elif ! command -v visudo >/dev/null 2>&1; then
    warn "visudo not found (sudo not installed?); updater sudo grants not written"
else
    tmp="${SUDOERS}.tmp.$$"
    cat > "${tmp}" <<SUDOEOF
# Generated by ZenPlus setup-updater-privileges.sh — do not edit by hand.
# Lets the zenplus service account queue an update check and set the check
# interval. The helper validates the number and writes a fixed timer drop-in.
${SERVICE_USER} ALL=(root) NOPASSWD: /bin/systemctl --no-block start zenplus-updater.service
${SERVICE_USER} ALL=(root) NOPASSWD: /bin/systemctl start zenplus-updater.service
${SERVICE_USER} ALL=(root) NOPASSWD: ${HELPER_DST} set-interval *
SUDOEOF
    chown root:root "${tmp}"
    chmod 0440 "${tmp}"
    # Validate before moving into place: a bad sudoers file breaks sudo.
    if visudo -cf "${tmp}" >/dev/null 2>&1; then
        mv -f "${tmp}" "${SUDOERS}"
        log "Sudoers grant installed and validated (no free-form timer write)"
    else
        rm -f "${tmp}"
        warn "sudoers validation failed; ${SUDOERS} left unchanged"
        exit 1
    fi
fi

# ── 3. Existing timer drop-in ───────────────────────────────────────────────
# Keep an administrator's interval, in the fixed form. A drop-in that is not a
# plain managed interval (possible while the tee grant existed) is removed.
# A failure here (an unexpected directory or symlink) is reported, not fatal:
# the free-form grant is already gone, and the update must not roll back for it.
"${HELPER_DST}" reconcile || warn "timer drop-in could not be reconciled; inspect /etc/systemd/system/zenplus-updater.timer.d"

# ── 4. polkit ───────────────────────────────────────────────────────────────
polkit_changed=0
for pkla in /etc/polkit-1/localauthority/50-local.d/zenplus-updater.pkla \
            /var/lib/polkit-1/localauthority/50-local.d/zenplus-updater.pkla; do
    if [ -e "${pkla}" ] || [ -L "${pkla}" ]; then
        rm -f "${pkla}"
        polkit_changed=1
        log "Removed legacy all-units polkit grant ${pkla}"
    fi
done

# polkit >= 0.106 understands JavaScript .rules (0.105 is the last pkla-only
# release; from 121 the version has no "0." prefix).
polkit_ver=$(pkaction --version 2>/dev/null | grep -oE '[0-9]+(\.[0-9]+)*' | head -n 1 || true)
polkit_major=${polkit_ver%%.*}
polkit_minor=0
case "${polkit_ver}" in *.*) polkit_minor=$(echo "${polkit_ver}" | cut -d. -f2) ;; esac
rules_capable=0
if [ -n "${polkit_major}" ]; then
    if [ "${polkit_major}" -gt 0 ] 2>/dev/null || [ "${polkit_minor:-0}" -ge 106 ] 2>/dev/null; then
        rules_capable=1
    fi
fi
if [ "${rules_capable}" -eq 1 ] && [ -f "${RULES_SRC}" ]; then
    install -d -m 0755 /etc/polkit-1/rules.d
    if ! cmp -s "${RULES_SRC}" /etc/polkit-1/rules.d/50-zenplus-updater.rules; then
        install -o root -g root -m 0644 "${RULES_SRC}" /etc/polkit-1/rules.d/50-zenplus-updater.rules
        polkit_changed=1
        log "Installed narrow polkit rule (updater units only, polkit ${polkit_ver})"
    fi
else
    log "polkit ${polkit_ver:-not found}: no polkit grant installed; the API uses sudo"
fi
if [ "${polkit_changed}" -eq 1 ]; then
    systemctl try-restart polkit.service 2>/dev/null || true
fi

log "Updater privileges configured"
